"""Rehearsed inferential extension for the Oklahoma county wheat fallback (Stop 2).

Model: a linear trend in county winter wheat yield over 2000 to 2025 with a
fixed effect for each county, and standard errors clustered by year, because a
drought or a good spring hits every county in the same year at once.

Run from the labs/ folder:

    python 02_data/datasets/oklahoma-wheat/reference/extension.py
"""
from pathlib import Path

import pandas as pd
import statsmodels.formula.api as smf

HERE = Path(__file__).resolve().parent
RAW = HERE.parent / "ok_county_winter_wheat_2000-2025.csv"
OUT = HERE / "extension.md"

raw = pd.read_csv(RAW, dtype=str, keep_default_na=False)
y = raw[(raw["STATISTICCAT_DESC"] == "YIELD")
        & (raw["PRODN_PRACTICE_DESC"] == "ALL PRODUCTION PRACTICES")
        & (raw["COUNTY_CODE"] != "998")].copy()
d = pd.DataFrame({
    "yield_": pd.to_numeric(y["VALUE"].str.replace(",", "", regex=False)),
    "year": y["YEAR"].astype(int),
    "county": y["COUNTY_NAME"].str.title(),
})
d["decade"] = (d["year"] - 2000) / 10  # slope reads as bushels per acre per decade
n, n_counties, n_years = len(d), d["county"].nunique(), d["year"].nunique()
print(f"county-years={n} counties={n_counties} years={n_years}")

by_year = {"cov_type": "cluster", "cov_kwds": {"groups": pd.factorize(d["year"])[0]}}
naive = smf.ols("yield_ ~ decade", data=d).fit()
pooled = smf.ols("yield_ ~ decade", data=d).fit(**by_year)
fe = smf.ols("yield_ ~ decade + C(county)", data=d).fit(**by_year)
fe_naive = smf.ols("yield_ ~ decade + C(county)", data=d).fit()

def row(fit):
    lo, hi = fit.conf_int().loc["decade"]
    return fit.params["decade"], fit.bse["decade"], lo, hi, fit.pvalues["decade"]

r = {k: row(f) for k, f in [("naive", naive), ("pooled", pooled), ("fe_naive", fe_naive), ("fe", fe)]}
for k, (b, se, lo, hi, p) in r.items():
    print(f"{k:9s} trend={b:+.2f} bu/ac per decade SE={se:.2f} 95% CI [{lo:+.2f}, {hi:+.2f}] p={p:.2g}")
b, se, lo, hi, p = r["fe"]

# The residual swing from year to year, after county and trend.
year_means = (d.assign(resid=fe.resid).groupby("year")["resid"].mean())
sd_year = year_means.std()
print(f"sd of year shocks after county and trend = {sd_year:.1f} bu/ac")

def fmt(k):
    b_, se_, lo_, hi_, p_ = r[k]
    return f"{b_:+.2f} | {se_:.2f} | {lo_:+.2f} to {hi_:+.2f} | {p_:.2g}"

OUT.write_text(f"""# Extension: is there a trend in county wheat yield, 2000 to 2025?

Generated by extension.py. Ordinary least squares of county winter wheat yield (bushels per
harvested acre) on harvest year, {n} county-years from {n_counties} counties and {n_years} years.
The slope is in bushels per acre per decade.

| Model | Trend (bu/ac per decade) | SE | 95% CI | p |
|---|---|---|---|---|
| yield ~ year, ordinary SE | {fmt('naive')} |
| yield ~ year, SE clustered by year | {fmt('pooled')} |
| yield ~ year + county, ordinary SE | {fmt('fe_naive')} |
| yield ~ year + county, SE clustered by year | {fmt('fe')} |

With a fixed effect for each county and errors clustered by year, the trend is {b:+.2f}
bushels per acre per decade (95% CI {lo:+.2f} to {hi:+.2f}, p = {p:.2g}). The year-to-year
swing left after county and trend has a standard deviation of {sd_year:.1f} bushels per acre,
so over these 25 harvests weather dominates any trend.

Why this model. The outcome is a continuous yield; the comparison is time. County fixed
effects compare each county with itself, which handles the confounder in the four lines:
NASS published fewer counties after 2007, so a plain statewide average mixes a change in
yield with a change in which counties are averaged. Errors are clustered by year because
counties in the same year share the same weather; ordinary standard errors treat them as
independent and here come out {r['fe'][1] / r['fe_naive'][1]:.1f} times too small (compare the last two rows).

Assumptions. A straight-line trend, the same in every county; county differences constant
over time; year shocks independent of one another. With {n_years} year clusters the
clustered intervals are approximate. Yield is per harvested acre, and the harvested share
of planted acres varies from year to year (grazing and abandonment), so this is a trend in
harvested yield, not in what was planted.
""")
print(f"written: {OUT.name}")
