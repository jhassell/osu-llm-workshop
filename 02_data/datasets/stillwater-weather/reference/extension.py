"""Rehearsed inferential extension for the Stillwater weather fallback (Stop 2).

Model: ordinary least squares of the daily high on a rain indicator with month
and year fixed effects, and Newey-West (HAC) standard errors, because today's
temperature is strongly correlated with yesterday's and ordinary standard
errors assume independent days.

Run from the labs/ folder:

    python 02_data/datasets/stillwater-weather/reference/extension.py
"""
import calendar
from pathlib import Path

import pandas as pd
import statsmodels.formula.api as smf

HERE = Path(__file__).resolve().parent
RAW = HERE.parent / "stillwater_daily_2021-2025.csv"
OUT = HERE / "extension.md"
LAGS = 7  # a week of serial correlation

raw = pd.read_csv(RAW, parse_dates=["DATE"])
d = raw.dropna(subset=["TMAX", "PRCP"]).sort_values("DATE").copy()
d["wet"] = (d["PRCP"] >= 0.01).astype(int)
d["month"] = d["DATE"].dt.month
d["year"] = d["DATE"].dt.year
lag1 = d["TMAX"].autocorr(lag=1)
print(f"days={len(d)} lag-1 autocorrelation of TMAX={lag1:.2f}")

naive = smf.ols("TMAX ~ wet", data=d).fit()
hac = {"cov_type": "HAC", "cov_kwds": {"maxlags": LAGS}}
raw_hac = smf.ols("TMAX ~ wet", data=d).fit(**hac)
adj = smf.ols("TMAX ~ wet + C(month) + C(year)", data=d).fit(**hac)
adj_ols = smf.ols("TMAX ~ wet + C(month) + C(year)", data=d).fit()

def row(fit):
    lo, hi = fit.conf_int().loc["wet"]
    return fit.params["wet"], fit.bse["wet"], lo, hi, fit.pvalues["wet"]

r = {name: row(f) for name, f in [("naive", naive), ("raw_hac", raw_hac), ("adj_ols", adj_ols), ("adj", adj)]}
for name, (b, se, lo, hi, p) in r.items():
    print(f"{name:8s} wet effect={b:+.2f} F SE={se:.2f} 95% CI [{lo:+.2f}, {hi:+.2f}] p={p:.2g}")
b, se, lo, hi, p = r["adj"]

# Month-by-month gaps, to say where the single average effect hides variation.
gaps = d.groupby(["month", "wet"])["TMAX"].mean().unstack()
gaps = (gaps[1] - gaps[0]).sort_values()
top = [calendar.month_name[m] for m in sorted(gaps.index[:3])]
largest = ", ".join(top[:-1]) + " and " + top[-1]
smallest = calendar.month_name[gaps.index[-1]]
print(f"largest monthly gaps: {largest}; smallest: {smallest} ({gaps.iloc[-1]:+.1f} F)")

OUT.write_text(f"""# Extension: how much cooler is a rainy day, same month and year?

Generated by extension.py. Ordinary least squares of the daily high (F) on an indicator
for measurable rain (0.01 inch or more), {len(d)} days.

| Model | Rain effect (F) | SE | 95% CI | p |
|---|---|---|---|---|
| high ~ rain, ordinary SE | {r['naive'][0]:+.2f} | {r['naive'][1]:.2f} | {r['naive'][2]:+.2f} to {r['naive'][3]:+.2f} | {r['naive'][4]:.2g} |
| high ~ rain, HAC SE | {r['raw_hac'][0]:+.2f} | {r['raw_hac'][1]:.2f} | {r['raw_hac'][2]:+.2f} to {r['raw_hac'][3]:+.2f} | {r['raw_hac'][4]:.2g} |
| high ~ rain + month + year, ordinary SE | {r['adj_ols'][0]:+.2f} | {r['adj_ols'][1]:.2f} | {r['adj_ols'][2]:+.2f} to {r['adj_ols'][3]:+.2f} | {r['adj_ols'][4]:.2g} |
| high ~ rain + month + year, HAC SE | {b:+.2f} | {se:.2f} | {lo:+.2f} to {hi:+.2f} | {p:.2g} |

Holding month and year fixed, a day with measurable rain has a high about {abs(b):.1f} F
{'lower' if b < 0 else 'higher'} than a dry day (95% CI {lo:+.1f} to {hi:+.1f} F). The month
effects take out the seasonal cycle that confounds the raw comparison.

Why this model. The outcome is a continuous daily temperature, the comparison is a yes or
no, and the confounder (season) is handled by month fixed effects; year fixed effects
absorb a warm or cool year. The rows are a time series, not independent draws: the lag-1
autocorrelation of the daily high is {lag1:.2f}, so standard errors use Newey-West with
{LAGS} lags. Here they move the standard error from {r['adj_ols'][1]:.2f} to {se:.2f}: rain
days themselves are not strongly clustered, so the correction is small, but it is the
check to run before trusting any p-value from daily data.

Assumptions. The rain effect is the same in every month (figure 2 shows the largest gaps in
{largest} and the smallest in {smallest}, so this is an average); month effects are the same each year;
serial correlation dies out within about a week; the two absent July 2025 dates and the
dropped blank days are treated as if the series were continuous. This is an association
at one station, not a causal effect of rain: clouds, fronts and rain arrive together.
""")
print(f"written: {OUT.name}")
