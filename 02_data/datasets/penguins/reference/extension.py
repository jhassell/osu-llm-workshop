"""Rehearsed inferential extension for the palmerpenguins fallback (Stop 2).

Model: ordinary least squares of bill depth on bill length, first pooled, then
with a separate intercept for each species, then with a separate slope too.
Standard errors are clustered by nest, because the two adults of a nest are a
mated pair and are not independent observations.

Run from the labs/ folder:

    python 02_data/datasets/penguins/reference/extension.py
"""
from pathlib import Path

import numpy as np
import pandas as pd
import statsmodels.formula.api as smf

HERE = Path(__file__).resolve().parent
RAW = HERE.parent / "penguins_raw.csv"
OUT = HERE / "extension.md"

raw = pd.read_csv(RAW)
d = pd.DataFrame({
    "depth": raw["Culmen Depth (mm)"],
    "length": raw["Culmen Length (mm)"],
    "species": raw["Species"].str.split().str[0],
    # "N12A2" is adult 2 of nest 12; nest numbers restart each season and species.
    "nest": raw["studyName"] + "-" + raw["Species"].str.split().str[0] + "-" + raw["Island"]
            + "-" + raw["Individual ID"].str.extract(r"^(N\d+)", expand=False),
}).dropna()
n_birds, n_nests = len(d), d["nest"].nunique()
print(f"birds={n_birds} nests={n_nests} largest nest group={d['nest'].value_counts().max()}")

cl = {"cov_type": "cluster", "cov_kwds": {"groups": pd.factorize(d["nest"])[0]}}
pooled = smf.ols("depth ~ length", data=d).fit(**cl)
adjusted = smf.ols("depth ~ length + C(species)", data=d).fit(**cl)
interact = smf.ols("depth ~ length * C(species)", data=d).fit(**cl)

def line(fit):
    b, se = fit.params["length"], fit.bse["length"]
    lo, hi = fit.conf_int().loc["length"]
    return b, se, lo, hi, fit.pvalues["length"], fit.rsquared

p_b, p_se, p_lo, p_hi, p_p, p_r2 = line(pooled)
a_b, a_se, a_lo, a_hi, a_p, a_r2 = line(adjusted)
print(f"pooled:   slope={p_b:.4f} SE={p_se:.4f} 95% CI [{p_lo:.4f}, {p_hi:.4f}] p={p_p:.2g} R2={p_r2:.3f}")
print(f"adjusted: slope={a_b:.4f} SE={a_se:.4f} 95% CI [{a_lo:.4f}, {a_hi:.4f}] p={a_p:.2g} R2={a_r2:.3f}")

# Do the species need different slopes? Wald test that both interaction terms are zero.
# With clustered errors statsmodels reports this as a chi-squared statistic.
names = [n for n in interact.params.index if n.startswith("length:")]
R = np.zeros((len(names), len(interact.params)))
for i, n in enumerate(names):
    R[i, list(interact.params.index).index(n)] = 1
wald = interact.wald_test(R, scalar=True)
w_stat, w_p = float(wald.statistic), float(wald.pvalue)
print(f"equal-slopes test: chi2({len(names)})={w_stat:.2f} p={w_p:.3f}")

OUT.write_text(f"""# Extension: does bill depth rise with bill length once species is held fixed?

Generated by extension.py. Ordinary least squares, standard errors clustered by nest
({n_birds} birds in {n_nests} nests).

| Model | Slope on length (mm/mm) | Clustered SE | 95% CI | p | R squared |
|---|---|---|---|---|---|
| depth ~ length | {p_b:.3f} | {p_se:.3f} | {p_lo:.3f} to {p_hi:.3f} | {p_p:.2g} | {p_r2:.2f} |
| depth ~ length + species | {a_b:.3f} | {a_se:.3f} | {a_lo:.3f} to {a_hi:.3f} | {a_p:.2g} | {a_r2:.2f} |

Adding species as a separate intercept flips the slope from negative to positive and
raises R squared from {p_r2:.2f} to {a_r2:.2f}. A test that the three species share one
slope gives a Wald chi-squared of {w_stat:.2f} on {len(names)} df, p = {w_p:.3f}, so a common slope with species intercepts
is a reasonable summary.

Why this model. The outcome is continuous and roughly symmetric within species, the
relationship looks linear in each panel of figure 3, and species is the confounder named
in the four lines, so it enters as a fixed effect.

Assumptions. Linearity and similar spread of residuals within each species; birds
independent except within a nest, which is why the standard errors are clustered by
nest (two adults of a mated pair share a site, a season and a diet). Birds measured in
different seasons are treated as independent, and the sample is study nests near Palmer
Station, not a random sample of each species.
""")
print(f"written: {OUT.name}")
